def get_country_info(number: str) -> tuple:
    """
    Look up country flag and ISO code from a phone number.
    Matches longest prefix first for accuracy.
    Returns custom Telegram animated emoji if present in CUSTOM_FLAGS.
    """
    for prefix, flag, code in COUNTRY_CODES:
        if number.startswith(prefix):
            custom_id = CUSTOM_FLAGS.get(flag)
            if custom_id:
                flag = f'<tg-emoji emoji-id="{custom_id}">{flag}</tg-emoji>'
            return flag, code
    return "🌍", "UN"
